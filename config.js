window.POKE_CONFIG = {
    // ---- 基本 ----
    count: 4,           // 同時生成的寶可夢數量
    minId: 1,           // 寶可夢圖鑑編號起始 (1 = 妙蛙種子)
    maxId: 649,         // 圖鑑編號結束 (第五世代 649 以內才有動態 GIF，效果最好)

    // ---- 色違 ----
    // 每一隻「獨立」擲骰決定是否為色違，中獎的登場時會冒出金色閃光對話框。
    // 這裡刻意調成 1/100（平均 100 隻出 1 隻；以 count: 4 計算，
    // 每次重新整理約有 4% 機會至少出現 1 隻色違），直播才熱鬧得起來。
    // 想回到原作手感就改 1 / 4096（現代正作原生機率，第五世代原作其實是 1/8192）
    shinyChance: 1 / 100,
    shinyBurstDuration: 1400, // 色違星星特效的飛散＋淡出總時長 ms
    // 星星特效的飛散範圍倍率：星星從本體正中心向外炸開，這是炸多遠的倍率。
    // 2 = 範圍加倍、0.5 = 縮小一半；只調範圍，星星本身大小不變
    shinyBurstScale: 1,
    // 星星特效除了登場放一輪，之後每隔這個區間內的隨機秒數「重播」一輪——
    // 開頁那一下沒看到（或中途才進來）的人也不會錯過
    shinyBurstDelay: { min: 15000, max: 20000 },

    // ---- 主題地面 ----
    // 在頁面最底鋪一條像素地面，讓散步有地方踩，寶可夢會站上去。
    // 'random' = 每次載入隨機抽一種（預設，狂按 F5 就是輪盤；
    //            隨機池 = 七種地形 + 無地板，所以也可能抽到沒有地面）
    // 'none' = 關閉（維持全透明背景，給完全不想要主題地面的嵌入方）
    // 其他選項：'grass' 草地 / 'water' 水域 / 'snow' 雪地 / 'sand' 沙灘 /
    // 'rock' 岩地 / 'dirt' 土徑 / 'lava' 熔岩（水域與熔岩會緩慢流動）
    // 貼片圖樣載入時隨機生成，就算同一種地形每次也長得不太一樣
    theme: 'random',
    // 地面高度 px。內部以 2px 像素格繪製，實際高度會取到最接近的偶數
    themeHeight: 12,

    // ---- 天氣 ----
    // 主題地面決定天氣種類：雨（草地/水域/岩地/土徑，斜斜細細長長的藍色雨絲）、
    // 雪（雪地，白色小點慢慢飄、左右搖曳）、風沙（沙灘，橫向沙痕順風橫掃）、
    // 火星（熔岩，橘黃小火星從低處上飄漸滅）。每次載入擲一次骰，
    // 中了整頁就下著這場天氣；風向（雨的斜向、沙的走向）每次隨機一邊。
    // 粒子全用 CSS 動畫循環，不吃主迴圈效能；theme: 'none' 沒有場景就沒有天氣。
    // 0 = 永遠晴天
    weatherChance: 0.5,
    // 粒子密度倍率：雨絲/雪花/沙痕/火星的數量 = 基準（依視窗寬換算）× 這個值。
    // 2 = 傾盆大雨、0.5 = 毛毛雨
    weatherDensity: 1,

    // ---- 客串事件 ----
    // 三層機率：每隔 flybyDelay 區間內的隨機秒數擲骰一次，flybyChance 決定該次
    // 是否觸發；觸發時從「飛行系池」平均抽一隻（flybyLegendaryChance 的極低機率
    // 改抽「會飛的傳說池」——兩池全員任一屬性槽都含飛行，固拉多不會飛就不會亂入），
    // 沿隨機斜線航道、浮浮沉沉地從畫面外高速橫越、不加入常駐陣容。
    // 名單在 pokemon_cameo.js；色違吃全頁同一個 shinyChance，中了會拖金色星塵尾跡
    flybyDelay: { min: 15000, max: 20000 }, // 下一次擲骰的間隔區間 ms
    flybyChance: 0.25,           // 每次擲骰真的觸發客串的機率（0 = 整個機制關閉）
    flybyLegendaryChance: 0.05,  // 觸發時抽中「傳說池」而非「飛行池」的機率
    // 觸發時改派「信使鳥空投」的機率：信使鳥叼著果實橫越，半路鬆爪掉下一顆，
    // 之後就是一般的餵食流程（最近且有空的那隻冒驚嘆號跑去吃）。
    // 那一刻沒隻有空就整顆叼走；berry: 'off' 時不派這趟任務。0 = 關閉
    flybyDeliveryChance: 0.2,
    flybySpeed: 5,               // 橫越速度 px/幀（60fps 基準），實際每次 ±15% 隨機

    // ---- postMessage 遙控 ----
    // 父頁面（或 OBS 的 wrapper 頁）可隔著 iframe 用 postMessage 下指令，例：
    //   frame.contentWindow.postMessage({ ns: 'poke-stroll', cmd: 'poke' }, '*')
    // 指令：spawn 客串一隻（可帶 id；帶 delivery: true 改派信使鳥空投）/
    //       poke 開心跳（可帶 id）/ burst 色違星星重播 /
    //       join 加一隻常駐（可帶 id）/ leave 送走一隻常駐（可帶 id）/
    //       feed 天降果實（可帶 count）/ roster 查詢目前陣容（id/色違/體型）。
    // 每道指令都會回執（{ ns, re, ok, ... }）。串接方法見 PARAMS.md 的
    // 「postMessage 遙控」一節（部署站的 params.html 同步收錄，含現場試玩按鈕）
    remote: 'on',        // 'off' = 完全不理會遙控訊息
    remoteRateLimit: 10, // 每秒最多處理幾道指令，超過的直接丟棄（防高頻洗版）

    // ---- 丟果實餵食 ----
    // 滑鼠分流：左鍵按「本體」= 抓起來拖著走（見下方「滑鼠拖曳」）、
    // 右鍵點「本體」= 戳戳互動、左鍵點「空白處」= 從點擊位置掉下一顆像素樹果，
    // 距離最近且「有空」的那隻冒出驚嘆號發現它，跑過來三口吃掉 + 冒愛心。
    // 一隻只追一顆：流程中（發現 → 跑去 → 吃 → 愛心）不會發現其他果實，
    // 所以同時最多「常駐數量」顆（count=4 就最多 4 顆），大家都在忙就丟不出新的。
    // OBS 用來源的「互動」視窗玩；iframe 預設 pointer-events: none 點不到（見 README）
    berry: 'on', // 'off' = 點空白處無事發生
    // 空中搶食：左鍵點空白處丟果實時，被指派的那隻若離果實落點「超過
    // snatchDistance」，有 snatchChance 的機率被盯上——牠照常起跑（看不出
    // 異狀），跑完一半路程時一隻飛行系從果實那一側的畫面外進場，牠再冒
    // 一次驚嘆號原地停步，賊鳥沿 V 字軌跡俯衝叼走果實（還在半空也接得住），
    // 再沿進場角度的鏡像斜上遠走高飛——越飛越小、越飛越淡，彷彿真的飛遠了。
    // 目擊的那隻在被叼走那一刻換成一團黑線，沮喪個幾秒才回去散步；
    // 其他成員照常散步。與飛行系客串互相獨立；一次只演一場；
    // 遙控 feed 與信使鳥空投的果實不受影響。
    // 追果實的那隻被滑鼠抓走時果實沒人護著，伏筆會立刻兌現——賊鳥直接
    // 出手，被抓著的苦主忙著掙扎，不驚嘆也不黑線；放手若還來得及落地
    // 撞見俯衝，照舊補演目擊戲。0 = 關閉
    snatchChance: 0.25,
    // 搶食的距離門檻 px：超過才可能被搶。門檻內絕對安全——果實丟在腳邊
    // 護得住，丟得越遠越可能被半路攔截，餵食因此有了取捨。0 = 每顆都可能被搶
    snatchDistance: 150,
    // 賊鳥的速度與縮淡，四段各自可調：
    // 進場（俯衝）與離場（遠走）速度是「巡航（flybySpeed）的倍率」，
    // 離場比進場快一點 = 得手後加速逃逸的手感
    snatchDiveRate: 1.6, // 俯衝速度倍率（愈大衝得愈快）
    snatchFleeRate: 1.8, // 遠走速度倍率（愈大逃得愈快）
    // 縮小與變淡是「倍速」：1 = 基準（各花 2.4 秒走完）、2 = 兩倍快、
    // 0.5 = 半速拉長餘韻、0 = 凍住（不縮小 / 不變淡，直到飛出畫面）。
    // 兩者分開計時，可以只調其中一個；透明度淡完或飛出畫面，先到者收場
    snatchShrinkRate: 1, // 縮小倍速（透視感：越飛越小）
    snatchFadeRate: 1,   // 變淡倍速（越飛越透明）

    // ---- 滑鼠拖曳 ----
    // 左鍵按在寶可夢身上就把牠「抓起來」——按下的那一刻立刻跟手（刻意不設
    // 長按門檻：門檻期間身體不動、游標卻繼續走，那段距離會被凍進偏移量裡，
    // 整段拖曳都差一截）。跟著游標走、在手上掙扎，放開手才自由落體回地面。
    // 抓在手上的那隻等於暫時離場：不散步、不冒對話框、不寒暄、戳不動，
    // 新的果實也不會指派給牠（空投與遙控 feed 都會跳過，寧可整顆叼走）。
    // 追到一半的那顆不沒收：果實留在原地等牠，放手落地就回去續追——
    // 代價是落地時依「新的距離」重擲搶食的骰（snatchChance），
    // 被抓去遠方再放開，遠的距離就要面對遠的風險。
    // 游標拉出活動範圍（bounds）時牠貼著邊界繼續掙扎，不會被拖出場外
    drag: 'on',        // 'off' = 抓不起來，右鍵的戳戳互動不受影響
    // 掙扎動畫的倍速：2 = 兩倍快，0 = 抓起來但不掙扎。
    // 註：GIF 本身的播放速率瀏覽器不開放 JS 控制，所以掙扎感是 widget 自己畫的
    // 擺盪 + 上下抖動，這個值調的是那套動畫的速度
    dragStruggleRate: 2,

    // ---- 移動 ----
    baseSpeed: 0.25,    // 基礎移動速度 (px/幀，以 60fps 為基準)
    speedVariance: 0.25,// 個體間的速度差異上限（實際速度 = baseSpeed ~ baseSpeed + variance）

    // ---- 活動範圍（X 軸邊界）----
    // 以整個頁面寬度為 1 的比例表示，不論在電腦、手機、OBS 上都等比生效。
    // 例如 { min: 0.1, max: 0.9 } = 只在畫面中間 80% 的區域活動
    bounds: { min: 0.1, max: 0.9 },

    // ---- 發呆 ----
    idleChance: 0.01,   // 每一幀進入發呆狀態的機率
    lookTime: { min: 2000, max: 5000 }, // 發呆(看向我們)的時間範圍 ms
    bubbleChance: 1 / 3, // 發呆時冒出心情對話框的機率（愛心/音符/黑線/大便/Zzz/驚嘆號/問號/金色閃光 八選一）
    bubblePosition: 'side', // 對話框位置：'top' 頭頂正上方 / 'side' 面向方向的側邊 / 'none' 完全不顯示
    // 對話框在本體的上層還是下層：
    // 'front'  = 蓋在寶可夢身上（預設，像遊戲裡角色講話的對話框，遮到一點身體是正常的）
    // 'behind' = 躲在寶可夢後面（想完全不遮到本體時用）
    bubbleLayer: 'front',
    // 'side' 模式下，本體邊緣與對話框之間的左右空隙。
    // 單位是「點陣圖上的像素」，會跟著對話框的放大倍率縮放（小/中體型 2x、大體型 3x），
    // 所以 -5 實際上是 -10px（小/中）與 -15px（大）——這樣大小隻看起來的鬆緊才一致。
    // 預設是負數（往身體上疊）：搭配 bubbleLayer: 'front'，對話框壓在身體邊緣、
    // 尾巴的尖端落在本體身上，才像遊戲裡角色在講話。
    // 0 = 剛好貼齊身體邊緣；正數 = 整個框推到身體外面完全不重疊
    bubbleSideGap: -5,
    // 'side' 模式下的垂直微調 px：對話框底邊本來錨在「身高六成」處，
    // 這個值再往上加（負數往下）。單位是螢幕 px，不跟著放大倍率縮放，
    // 因為六成的錨點已經是等比例的，這裡只是收尾的幾個像素。0 = 不調整
    bubbleSideLift: 2,
    // 發呆亂跳：發呆時每一幀觸發「原地開心跳一下」的機率（跟被點擊時同一種小跳）。
    // 0.003 ≈ 每次發呆約有一半機會跳個一兩下；0 = 關閉
    idleJumpChance: 0.003,

    // ---- 走路跳步動畫 ----
    hopHeight: 3,        // 基礎跳躍高度 px
    hopVariance: 2,      // 個體間的跳躍高度差異上限
    hopFrequency: 0.005, // 跳步頻率（數字越小跳越慢）

    // ---- 互動 ----
    personalSpace: 56,   // 同伴間的最小距離 px：前方太近有同伴就掉頭，避免黏在一起
    // 偶遇打招呼：兩隻擦肩擠進 personalSpace 時，雙方都有空的話有這個機率
    // 不掉頭、改停下來寒暄——先各退到「彼此身寬 + 一點空隙」的站位（身體
    // 不會疊在一起），面對面之後才冒對話框（各自擲骰出音符或愛心），
    // 聊個一兩秒再轉身走開。寒暄完有 8~15 秒冷卻，不會原地無限寒暄；0 = 關閉
    greetChance: 0.1,

    // ---- 屬性影子 ----
    // 影子寬度 = 寶可夢實際顯示寬度 × 這個比例。
    // 1 會跟本體同寬（略顯笨重），太小又撐不住接地感，0.85 ~ 0.95 之間最自然
    shadowWidthRatio: 0.9,

    // 影子依「主屬性」染色（編號對照表在 pokemon_types.js）。
    // 刻意全用暗色系：影子本來就該是暗的，亮色會太突兀。
    // 查不到屬性的 ID 一律用 default（原本的黑影）。
    typeShadowColors: {
        normal:   'rgba(95, 95, 90, 0.45)',    // 一般：灰
        fire:     'rgba(150, 45, 20, 0.48)',   // 火：暗紅
        water:    'rgba(20, 60, 140, 0.48)',   // 水：暗藍
        electric: 'rgba(140, 110, 0, 0.50)',   // 電：暗黃
        grass:    'rgba(30, 100, 40, 0.48)',   // 草：暗綠
        ice:      'rgba(30, 110, 125, 0.48)',  // 冰：暗青
        fighting: 'rgba(120, 30, 60, 0.48)',   // 格鬥：暗緋紅
        poison:   'rgba(100, 30, 120, 0.48)',  // 毒：暗紫
        ground:   'rgba(115, 80, 30, 0.48)',   // 地面：暗土棕
        flying:   'rgba(90, 90, 160, 0.45)',   // 飛行：暗薰衣草藍
        psychic:  'rgba(150, 40, 90, 0.48)',   // 超能力：暗桃紅
        bug:      'rgba(90, 110, 20, 0.48)',   // 蟲：暗橄欖綠
        rock:     'rgba(90, 80, 55, 0.48)',    // 岩石：暗卡其
        ghost:    'rgba(70, 50, 110, 0.50)',   // 幽靈：暗靛
        dragon:   'rgba(60, 30, 160, 0.48)',   // 龍：暗藍紫
        dark:     'rgba(50, 40, 35, 0.55)',    // 惡：近黑
        steel:    'rgba(70, 85, 100, 0.48)',   // 鋼：暗鐵灰藍
        fairy:    'rgba(160, 90, 120, 0.45)',  // 妖精：暗玫瑰
        default:  'rgba(0, 0, 0, 0.35)',       // 查不到屬性時的預設黑影
    },

    // ---- 體型分級 ----
    // 用官方圖鑑身高(公尺)分成大、中、小，資料來自 pokemon_heights.js
    baseSize: 128, // 「大」體型的顯示高度 px（中 = 0.8、小 = 0.6）
    sizeTiers: [
        { maxMeters: 0.8,      scale: 0.6 },  // 小：身高 < 0.8m
        { maxMeters: 1.5,      scale: 0.8 },  // 中：0.8m ~ 1.5m
        { maxMeters: Infinity, scale: 1 },    // 大：>= 1.5m
    ],
};
